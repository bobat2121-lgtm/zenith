// Builds the relationship bundle into worker/src/relations.generated.js (bundled
// into the Worker, like the rubric), read only through worker/src/relations.js.
// Inputs: rubric/peers.json (peer names, statuses and read-through signs),
// rubric/key-accounts.json (key-account names and kinds), registry/rivals.json
// (rival source keys per ticker) and worker/src/covered.json (the ticker list).
// Kept out on purpose: peers' why, status_note, matters and noise; key-account
// terms (they stay in the rubric's MATCH) and source; rivals' basis. This is
// relationship data from the rubric files, not register data.
// aux-sources.json is read only for a warning; it does not enter the output.
// `npm test` runs this script, so an input edit or a sync that changes the
// covered tickers regenerates the file; commit the regenerated file.
// Usage: node scripts/build-relations.mjs [--check] [--root=<dir>]
//   --check   write nothing; exit 1 when the file on disk differs
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { createHash } from "node:crypto";
import { join, dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

export const COMMAND = "node scripts/build-relations.mjs";
export const HEADER = "// GENERATED by scripts/build-relations.mjs — do not edit by hand.";
export const DIRECTIONS = ["-", "+", "±"];
const TOP_KEYS = ["basis", "peers", "rivals", "key_accounts"];

const own = (obj, key) => Object.prototype.hasOwnProperty.call(obj || {}, key);
const lf = (text) => String(text).replace(/\r\n?/g, "\n");
// U+2212 (minus sign) is written in some peer notes; the bundle uses ASCII "-".
const normDirection = (d) => (typeof d === "string" ? d.trim().replace(/−/g, "-") : d);

// RELATIONS_VERSION: "rel-" + 12 hex of sha256 over the three input files' LF
// text and the covered ticker list, so a sync that changes the tickers changes it.
export function relationsVersion({ peersText, keyAccountsText, rivalsText, tickers }) {
  const h = createHash("sha256");
  for (const part of [lf(peersText), lf(keyAccountsText), lf(rivalsText), JSON.stringify(tickers)]) h.update(part).update("\0");
  return "rel-" + h.digest("hex").slice(0, 12);
}

// Pure: parsed inputs -> { relations, warnings }. auxKeys (optional) only feeds a warning.
export function buildRelations({ peers, keyAccounts, rivals, tickers, auxKeys = null }) {
  const covered = new Set(tickers);
  const warnings = [];
  const out = { basis: "files", peers: {}, rivals: {}, key_accounts: {} };

  for (const p of Array.isArray(peers) ? peers : []) {
    const key = typeof p?.key === "string" ? p.key : "";
    if (!key) { warnings.push("a peers.json entry has no key"); continue; }
    if (own(out.peers, key)) { warnings.push(`peers.json key ${key} appears twice; the first is kept`); continue; }
    const reads = [];
    for (const r of Array.isArray(p.reads_through) ? p.reads_through : []) {
      const ticker = r?.ticker;
      if (!covered.has(ticker)) { warnings.push(`peers.json ${key} reads through ${ticker}, which is not covered`); continue; }
      const direction = normDirection(r.direction);
      if (!DIRECTIONS.includes(direction)) { warnings.push(`peers.json ${key} -> ${ticker} has direction ${JSON.stringify(r.direction)}; the link is left out`); continue; }
      if (reads.some((x) => x.ticker === ticker)) { warnings.push(`peers.json ${key} reads through ${ticker} twice; the first is kept`); continue; }
      reads.push({ ticker, direction });
    }
    out.peers[key] = { name: typeof p.name === "string" ? p.name : key, status: typeof p.status === "string" ? p.status : null, reads };
  }

  const auxSet = auxKeys ? new Set(auxKeys) : null;
  for (const [ticker, list] of Object.entries(rivals || {})) {
    if (!Array.isArray(list)) continue;
    if (!covered.has(ticker)) { warnings.push(`rivals.json lists ${ticker}, which is not covered`); continue; }
    const keys = [];
    for (const r of list) {
      const key = typeof r === "string" ? r : r?.key;
      if (typeof key !== "string" || !key) continue;
      if (keys.includes(key)) continue;
      if (auxSet && !own(out.peers, key) && !auxSet.has(key)) warnings.push(`rivals.json ${ticker} key ${key} is neither a peer key nor an aux source`);
      keys.push(key);
    }
    out.rivals[ticker] = keys;
  }

  for (const [ticker, list] of Object.entries(keyAccounts || {})) {
    if (!Array.isArray(list) || !covered.has(ticker)) continue;
    out.key_accounts[ticker] = list
      .filter((e) => typeof e?.name === "string" && e.name.trim())
      .map((e) => ({ name: e.name, kind: typeof e.kind === "string" ? e.kind : null }));
  }
  return { relations: out, warnings };
}

// One entry per line inside each map, so a diff shows the entry that changed.
export function renderRelations(version, relations) {
  const block = (obj) => {
    const lines = Object.entries(obj).map(([k, v]) => `${JSON.stringify(k)}:${JSON.stringify(v)}`);
    return lines.length ? `{\n${lines.join(",\n")}\n}` : "{}";
  };
  const body = `{\n"basis":${JSON.stringify(relations.basis)},\n"peers":${block(relations.peers)},\n"rivals":${block(relations.rivals)},\n"key_accounts":${block(relations.key_accounts)}\n}`;
  return `${HEADER}\nexport const RELATIONS_VERSION = ${JSON.stringify(version)};\nexport const RELATIONS = ${body};\n`;
}

// The generated text back to { version, relations }, or null when it is not in that format.
export function parseGenerated(text) {
  const t = lf(text);
  const v = /^export const RELATIONS_VERSION = (".*");$/m.exec(t);
  const at = t.indexOf("\nexport const RELATIONS = ");
  const r = at < 0 ? null : /^export const RELATIONS = (\{[\s\S]*\});\n?$/.exec(t.slice(at + 1));
  if (!v || !r) return null;
  try { return { version: JSON.parse(v[1]), relations: JSON.parse(r[1]) }; } catch { return null; }
}

export function readInputs(root) {
  const read = (...p) => readFileSync(join(root, ...p), "utf8");
  const peersText = read("rubric", "peers.json");
  const keyAccountsText = read("rubric", "key-accounts.json");
  const rivalsText = read("registry", "rivals.json");
  const tickers = JSON.parse(read("worker", "src", "covered.json")).tickers || [];
  const auxPath = join(root, "worker", "src", "aux-sources.json");
  const auxKeys = existsSync(auxPath) ? Object.keys(JSON.parse(readFileSync(auxPath, "utf8")).sources || {}) : null;
  return { peersText, keyAccountsText, rivalsText, tickers, auxKeys };
}

// Inputs on disk -> { version, relations, warnings, text }.
export function generate(root) {
  const inp = readInputs(root);
  const { relations, warnings } = buildRelations({
    peers: JSON.parse(inp.peersText), keyAccounts: JSON.parse(inp.keyAccountsText), rivals: JSON.parse(inp.rivalsText),
    tickers: inp.tickers, auxKeys: inp.auxKeys,
  });
  const version = relationsVersion(inp);
  return { version, relations, warnings, text: renderRelations(version, relations) };
}

function main(argv) {
  const rootArg = argv.find((a) => a.startsWith("--root="));
  const root = rootArg ? resolve(rootArg.slice(7)) : join(dirname(fileURLToPath(import.meta.url)), "..");
  const file = join(root, "worker", "src", "relations.generated.js");
  const { version, relations, warnings, text } = generate(root);
  for (const w of warnings) console.log(`WARNING ${w}`);

  if (argv.includes("--check")) {
    const disk = existsSync(file) ? readFileSync(file, "utf8") : null;
    if (disk === text) { console.log(`relations ${version}: worker/src/relations.generated.js is current`); return 0; }
    const parsed = disk === null ? null : parseGenerated(disk);
    let what;
    if (disk === null) what = "the file is missing";
    else if (!parsed) what = "the file is not in the generated format";
    else {
      const diff = [];
      if (parsed.version !== version) diff.push("RELATIONS_VERSION");
      for (const k of TOP_KEYS) if (JSON.stringify(parsed.relations?.[k]) !== JSON.stringify(relations[k])) diff.push(`RELATIONS.${k}`);
      for (const k of Object.keys(parsed.relations || {})) if (!TOP_KEYS.includes(k)) diff.push(`RELATIONS.${k} (not expected)`);
      what = diff.length ? `differs in ${diff.join(", ")}` : "differs in layout only";
    }
    console.log(`ERROR worker/src/relations.generated.js is stale: ${what}. Run ${COMMAND} and commit the result.`);
    return 1;
  }

  writeFileSync(file, text);
  const nKa = Object.values(relations.key_accounts).reduce((n, l) => n + l.length, 0);
  console.log(`relations ${version}: ${Object.keys(relations.peers).length} peers, rivals for ${Object.keys(relations.rivals).length} tickers, ${nKa} key accounts`);
  return 0;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) process.exitCode = main(process.argv.slice(2));
