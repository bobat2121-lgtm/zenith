// Builds the catalyst calendar from the company sheets into
// worker/src/calendar.generated.js (bundled into the Worker, like the rubric).
// Sources per sheet: open_items (target / expires_at), status_events, dated
// thesis_drivers and the "## Catalyst calendar" section.
// Usage: node scripts/build-calendar.mjs [--print]
import { readFileSync, readdirSync, existsSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { extractSheetCalendar } from "../worker/src/calendar.js";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const companiesDir = join(root, "rubric", "companies");
const covered = JSON.parse(readFileSync(join(root, "worker", "src", "covered.json"), "utf8"));

const entries = [];
const perTicker = {};
if (existsSync(companiesDir)) {
  for (const f of readdirSync(companiesDir).filter((f) => /^[A-Z]+\.md$/.test(f)).sort()) {
    const ticker = f.replace(/\.md$/, "");
    if (!covered.tickers.includes(ticker)) continue;
    const found = extractSheetCalendar(ticker, readFileSync(join(companiesDir, f), "utf8"));
    perTicker[ticker] = found.length;
    entries.push(...found);
  }
}
entries.sort((a, b) => (a.start || "").localeCompare(b.start || "") || a.ticker.localeCompare(b.ticker) || a.text.localeCompare(b.text));

const body = JSON.stringify(entries);
const version = "c-" + createHash("sha256").update(body).digest("hex").slice(0, 12);
writeFileSync(join(root, "worker", "src", "calendar.generated.js"),
  `// GENERATED by scripts/build-calendar.mjs from rubric/companies/*.md — do not edit by hand.
export const CALENDAR_VERSION = ${JSON.stringify(version)};
export const CALENDAR = ${body.replace(/\},\{/g, "},\n{")};
`);
const byKind = entries.reduce((m, e) => ((m[e.kind] = (m[e.kind] || 0) + 1), m), {});
const empty = covered.tickers.filter((t) => !perTicker[t]);
console.log(`calendar ${version}: ${entries.length} dated entries (${Object.entries(byKind).map(([k, n]) => `${k} ${n}`).join(", ")})`);
if (empty.length) console.log(`WARNING sheets with no dated entries: ${empty.join(", ")}`);
if (process.argv.includes("--print")) for (const e of entries) console.log(`${e.start || "weekly"}..${e.end || ""} ${e.precision}${e.approx ? "~" : ""}${e.context ? " ctx" : ""} ${e.ticker} [${e.kind}] ${e.text.slice(0, 110)}`);
